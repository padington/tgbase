// puSetsLine renders a plan as the user sees it — "7, 8, 6, 6, 9+", with the
// open set marked by its plus.
func puSetsLine(targets []int) string {
	if len(targets) == 0 {
		return ""
	}
	parts := make([]string, 0, len(targets))
	for i, n := range targets {
		s := strconv.Itoa(n)
		if i == len(targets)-1 {
			s += "+"
		}
		parts = append(parts, s)
	}
	return strings.Join(parts, ", ")
}

// puPlan generates the plan of the program's NEXT session. The day index is
// the position inside the week, so the three sessions of a week differ
// without any calendar being involved.
func puPlan(c *screening.PushupContent, p *state.PushupProgram) screening.PushupPlan {
	return c.Plan(screening.PlanInput{
		Base:         p.Base,
		DayIdx:       p.SessionInWeek,
		EffortAdj:    p.EffortAdj,
		Goal:         p.Goal,
		SessionsDone: p.SessionsDone,
		Deload:       p.Deload,
		RestBonusSec: p.RestBonusSec,
	})
}

// puPlanLine is the "Первая тренировка: 7, 8, 6, 6, 9+ — примерно 12 минут."
// line: what the next session looks like, in one line.
func puPlanLine(c *screening.PushupContent, p *state.PushupProgram) string {
	plan := puPlan(c, p)
	return renderContent(c.Test.PlanLine, map[string]string{
		"sets":    puSetsLine(plan.Targets),
		"minutes": strconv.Itoa(c.EstimateMinutes(plan)),
	})
}

// puVariationName is the rung's display name (its id as a fallback — an
// unknown id can only come from hand-edited state).
func puVariationName(c *screening.PushupContent, id string) string {
	if v := c.Variation(id); v != nil {
		return v.Name
	}
	return id
}

// puSum totals a slice of reps.
func puSum(values []int) int {
	total := 0
	for _, v := range values {
		total += v
	}
	return total
}

// puSparkline renders the last open sets as "9 ▁▂▂▃▄▄▅▇ 17" — the track's
// progress picture in one line of text. v1 has no image rendering by
// decision; the two numbers carry the scale the blocks cannot.
func puSparkline(history []state.PushupSessionLog, points int) string {
	values := make([]int, 0, points)
	for i := len(history) - 1; i >= 0 && len(values) < points; i-- {
		if history[i].OpenActual <= 0 {
			continue
		}
		values = append(values, history[i].OpenActual)
	}
	if len(values) == 0 {
		return ""
	}
	// Collected newest-first; the line reads oldest → newest.
	for i, j := 0, len(values)-1; i < j; i, j = i+1, j-1 {
		values[i], values[j] = values[j], values[i]
	}
	lo, hi := values[0], values[0]
	for _, v := range values {
		if v < lo {
			lo = v
		}
		if v > hi {
			hi = v
		}
	}
	var b strings.Builder
	for _, v := range values {
		idx := 0
		if hi > lo {
			idx = (v - lo) * (len(puSparkChars) - 1) / (hi - lo)
		} else {
			idx = len(puSparkChars) / 2
		}
		b.WriteRune(puSparkChars[idx])
	}
	return strconv.Itoa(lo) + " " + b.String() + " " + strconv.Itoa(hi)
}

