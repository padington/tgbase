// puBeginWorkout generates the session and enters the first set. Everything
// the session needs is frozen into it at this moment (targets, rest), so a
// base change mid-session cannot rewrite the numbers under the user.
func puBeginWorkout(c *screening.PushupContent, p *state.PushupProgram, now time.Time) Outcome {
	plan := puPlan(c, p)
	session := &state.PushupSession{
		Kind:        state.PushupSessionWorkout,
		DayIdx:      p.SessionInWeek,
		Targets:     append([]int(nil), plan.Targets...),
		OpenFloor:   plan.OpenFloor(),
		RestSec:     plan.RestSec,
		StartedAt:   now,
		ResumeState: state.StatePuSet,
	}
	return Outcome{
		NextState: state.StatePuSet,
		Mutate: func(u *state.UserData) {
			u.PuSession = session.Clone()
		},
	}
}

// puTestDue reports whether the next session must be a max test instead of a
// workout: the scheduled retest, one owed by an earlier regression, or a
// pause long enough that the old base is no longer a measurement.
func puTestDue(c *screening.PushupContent, p *state.PushupProgram, now time.Time) bool {
	if p.RetestPending || p.SessionsSinceTest >= c.Params.RetestEverySessions {
		return true
	}
	return puPauseDays(p, now) >= c.Params.PauseRetestDays
}

// puPauseDays is how many whole days have passed since the last session
// (0 when the program has none yet).
func puPauseDays(p *state.PushupProgram, now time.Time) int {
	if p.LastSessionAt.IsZero() {
		return 0
	}
	return int(now.Sub(p.LastSessionAt).Hours() / 24)
}

// puTrain decides what a "train now" tap does. It is the one place the
// track's safety rules live: a session cannot start twice in the recovery
// window (hard block), a due retest replaces the workout, and the weekly
// red-flag check-in runs before the first session of every week.
//
// force is the «Всё равно тренироваться» tap: it only skips the SOFT
// warning between min_hours_between and advised_hours_between, never the
// hard block below min_hours_between.
func puTrain(ctx Context, c *screening.PushupContent, force bool) Outcome {
	u, now := ctx.User, ctx.Now()
	p := u.Pushups
	if p == nil {
		return Outcome{NextState: state.StatePuConsent}
	}
	if s := puWorkoutSession(c, u, now); s != nil {
		// An open session is resumed, never silently replaced.
		return Outcome{NextState: puResumeTarget(c, u, now)}
	}
	if p.Base <= 0 {
		return Outcome{NextState: state.StatePuTest}
	}

	if !p.LastSessionAt.IsZero() {
		since := now.Sub(p.LastSessionAt)
		advised := time.Duration(c.Params.AdvisedHoursBetween) * time.Hour
		switch {
		case puWithinRecovery(c, p, now):
			// Hard block — the one rule force cannot buy through.
			return scrText(c.Session.RestDay)
		case since < advised && !force:
			oc := scrText(renderContent(c.Session.TooSoon, map[string]string{
				"hours":   strconv.Itoa(int(since.Hours())),
				"advised": strconv.Itoa(c.Params.AdvisedHoursBetween),
			}))
			oc.Keyboard = [][]string{{c.Session.TrainAnywayButton}, {homeLabel(ctx)}}
			return oc
		}
	}

	if puTestDue(c, p, now) {
		return Outcome{NextState: state.StatePuTest}
	}
	if p.SessionsDone > 0 && p.SessionInWeek == 0 {
		// Once a week, before the first session: the red-flag check-in.
		return Outcome{NextState: state.StatePuRedCard}
	}
	return puBeginWorkout(c, p, now)
}

// puWithinRecovery is the hard block: less than min_hours_between since the
// last session. It is a property of the PROGRAM, not of a button — every way
// of starting a session asks it, and nothing overrides it.
func puWithinRecovery(c *screening.PushupContent, p *state.PushupProgram, now time.Time) bool {
	if p.LastSessionAt.IsZero() {
		return false
	}
	return now.Sub(p.LastSessionAt) < time.Duration(c.Params.MinHoursBetween)*time.Hour
}

// puRetest decides what the menu's «Перетест» tap does. A max test IS a
// session of the week — it moves the base, counts as the day's work, closes
// the week and writes history — so it goes through the same hard recovery
// block as a workout. Without it the button was a way around the one rule
// the track sells as non-negotiable, and each tap also inflated the week
// counter and the streak.
//
// The SOFT 24–48 h warning is deliberately not re-asked here: reaching for
// «Перетест» on the menu is already the deliberate act that warning asks
// for, and its override button starts a workout, not a test.
func puRetest(ctx Context, c *screening.PushupContent) Outcome {
	u, now := ctx.User, ctx.Now()
	p := u.Pushups
	if p == nil {
		return Outcome{NextState: state.StatePuConsent}
	}
	if s := puWorkoutSession(c, u, now); s != nil {
		// An open session is resumed, never replaced by a test.
		return Outcome{NextState: puResumeTarget(c, u, now)}
	}
	if puWithinRecovery(c, p, now) {
		return scrText(c.Session.RestDay)
	}
	return Outcome{NextState: state.StatePuTest}
}

// puRecordReps writes one performed set and moves the session on: into the
// rest timer, or — after the last, open set — into the self-report question.
// Shared by the set phase and by the rest phase (a number sent during a rest
// means the user trained ahead of the timer, which must not be punished).
func puRecordReps(c *screening.PushupContent, u state.UserData, reps int, now time.Time) Outcome {
	s := u.PuSession
	if s == nil || len(s.Targets) == 0 {
		return Outcome{NextState: state.StatePuMenu}
	}
	idx := len(s.Actual)
	if idx >= len(s.Targets) {
		return Outcome{NextState: state.StatePuEffort}
	}
	last := idx == len(s.Targets)-1

	if !last {
		restUntil := now.Add(time.Duration(s.RestSec) * time.Second)
		// Silent on purpose: the "recorded N, rest M s" line belongs to the
		// rest phase's Setup, which fires right after this transition. That
		// keeps ONE message per set and makes the same line reappear —
		// with the REMAINING seconds — when a paused user comes back.
		oc := Outcome{NextState: state.StatePuRest}
		oc.Mutate = func(u *state.UserData) {
			mutatePuSession(u, func(s *state.PushupSession) {
				s.Actual = append(s.Actual, reps)
				s.Idx = len(s.Actual)
				s.RestUntil = restUntil
				s.ResumeState = state.StatePuRest
			})
		}
		return oc
	}

	// The open set closes the session: summarise, then ask the ONE
	// post-session question.
	actual := append(append([]int(nil), s.Actual...), reps)
	outcome := c.ClassifySession(s.Targets, actual)
	oc := scrText(puSummaryText(c, s, actual, outcome))
	oc.NextState = state.StatePuEffort
	oc.Mutate = func(u *state.UserData) {
		mutatePuSession(u, func(s *state.PushupSession) {
			s.Actual = append(s.Actual, reps)
			s.Idx = len(s.Actual)
			s.RestUntil = time.Time{}
			s.ResumeState = state.StatePuEffort
		})
	}
	return oc
}

// puSummaryText renders the two-number session summary. "Short" is a first
// class outcome: the session still counts, and the text says so.
func puSummaryText(c *screening.PushupContent, s *state.PushupSession, actual []int, outcome string) string {
	open := 0
	if len(actual) > 0 {
		open = actual[len(actual)-1]
	}
	args := map[string]string{
		"total": strconv.Itoa(puSum(actual)),
		"open":  strconv.Itoa(open),
		"extra": strconv.Itoa(open - s.OpenFloor),
	}
	switch outcome {
	case screening.PushupOutcomeOver:
		return renderContent(c.Session.SummaryOver, args)
	case screening.PushupOutcomePlan:
		return renderContent(c.Session.SummaryPlan, args)
	default:
		return renderContent(c.Session.SummaryShort, args)
	}
}

// puSessionLog builds the history entry of a finished session: numbers only,
// no free text — the ring lives inside the shared users.json.
func puSessionLog(c *screening.PushupContent, p *state.PushupProgram, s *state.PushupSession,
	effort string, now time.Time) state.PushupSessionLog {
	outcome := c.ClassifySession(s.Targets, s.Actual)
	open := 0
	if len(s.Actual) == len(s.Targets) && len(s.Actual) > 0 {
		open = s.Actual[len(s.Actual)-1]
	}
	return state.PushupSessionLog{
		Date:       now,
		DayIdx:     s.DayIdx,
		Sets:       append([]int(nil), s.Actual...),
		Planned:    puSum(s.Targets),
		Done:       puSum(s.Actual),
		OpenTarget: s.OpenFloor,
		OpenActual: open,
		Outcome:    outcome,
		Effort:     effort,
		Base:       p.Base,
	}
}

// puCloseSession is the shared bookkeeping of a finished session, applied to
// the program inside one Mutate: counters, the lifetime volume, the next due
// date and the week's outcome list. It does NOT close the week — that is
// puCloseWeek, which has a message to render.
func puCloseSession(c *screening.PushupContent, u *state.UserData, log state.PushupSessionLog, now time.Time) {
	mutatePuProgram(u, func(p *state.PushupProgram) {
		p.SessionsDone++
		p.SessionsSinceTest++
		p.TotalReps += log.Done
		p.LastSessionAt = now
		p.NextDueAt = now.Add(time.Duration(c.Params.AdvisedHoursBetween) * time.Hour)
		p.DuePingSent = false
		p.Deload = false // consumed by the session that just ran
		p.WeekOutcomes = append(p.WeekOutcomes, log.Outcome)
		p.SessionInWeek++
	})
	u.PuHistory = state.AppendPushupLog(u.PuHistory, log, c.Params.HistoryCap)
	u.PuSession = nil
}

// puWeekDue reports whether the week's last session has just been recorded.
func puWeekDue(c *screening.PushupContent, p *state.PushupProgram) bool {
	return p.SessionInWeek >= c.Params.SessionsPerWeek
}

// puCloseWeek applies the weekly rule to the program and returns the line
// that ANNOUNCES it. A repeated week is never silent: a base that quietly
// moves down reads as a bug, so the repeat text says what happened and why.
func puCloseWeek(c *screening.PushupContent, p *state.PushupProgram) string {
	old := p.Base
	wk := c.ProgressWeek(p.Base, p.WeekOutcomes)

	p.Base = wk.NewBase
	p.WeekIdx++
	p.SessionInWeek = 0
	p.WeekOutcomes = nil
	if wk.Repeat {
		p.RepeatCount++
	} else {
		p.RepeatCount = 0
	}
	if wk.StreakGrows {
		p.StreakWeeks++
	}

	args := map[string]string{
		"old":  strconv.Itoa(old),
		"new":  strconv.Itoa(wk.NewBase),
		"base": strconv.Itoa(wk.NewBase),
	}
	switch wk.Kind {
	case screening.PushupWeekStrong:
		return renderContent(c.Week.ClosedStrong, args)
	case screening.PushupWeekHold:
		return renderContent(c.Week.ClosedHold, args)
	case screening.PushupWeekRepeat:
		return renderContent(c.Week.Repeat, args)
	default:
		return renderContent(c.Week.ClosedSteady, args)
	}
}

// puExpired is what closing a stale session did: the line(s) to show and
// whether the week it closed was the third repeated one in a row.
type puExpired struct {
	Text string // "" when there was nothing to expire
	Fork bool   // the closed week hit repeat_fork_after
}

// puExpireSession closes an unfinished session that outlived the TTL: it is
// recorded by what was actually done (a partial session is a real session)
// and the automaton is freed.
//
// A session dying of old age can be the week's third one, so this is a
// second place the week can close — and the week's verdict is ALWAYS spoken
// out loud, on this path exactly as on the finished-session one. A base that
// drops in silence reads as a bug (it is the documented reason people call a
// program broken), and a third repeat in a row owes the user the fork
// instead of a fourth identical week.
func puExpireSession(c *screening.PushupContent, u *state.UserData, now time.Time) puExpired {
	s := u.PuSession
	if s == nil || !s.Stale(now, puSessionTTL(c)) {
		return puExpired{}
	}
	if s.Kind != state.PushupSessionWorkout || u.Pushups == nil || len(s.Actual) == 0 {
		// A dropped max test (or a session with no set recorded) leaves no
		// trace: there is nothing to count.
		u.PuSession = nil
		return puExpired{Text: c.Session.Expired}
	}
	log := puSessionLog(c, u.Pushups, s, "", s.StartedAt)
	puCloseSession(c, u, log, s.StartedAt)

	out := puExpired{Text: c.Session.Expired}
	if puWeekDue(c, u.Pushups) {
		var closing string
		mutatePuProgram(u, func(p *state.PushupProgram) { closing = puCloseWeek(c, p) })
		out.Text += "\n" + closing
		out.Fork = u.Pushups.RepeatCount >= c.Params.Progression.RepeatForkAfter
	}
	return out
}

// puWipeTrack clears every persisted trace of the pushup track.
func puWipeTrack(u *state.UserData) {
	u.PuConsentAt = nil
	u.Pushups = nil
	u.PuSession = nil
	u.PuTest = nil
	u.PuHistory = nil
}
