// Helpers shared by the pushup-track phases (pu_*.go). Like the three
// self-check tracks next door, every user-visible string comes from the
// content bundle (screening.PushupContent) and reaches the user through the
// "scr.text" pass-through i18n key — nothing user-visible is hardcoded here.
// Generic helpers (normText, labelIs, renderContent, scrText, testExitState,
// deleteReturnState, homeLabel) are shared with scr_common.go and mode.go.
//
// What makes this track different from its neighbours: it drives a PROGRAM,
// not a questionnaire. Every rep count on screen is generated by
// screening.Plan from ONE number (the base), the session lives across
// messages with a server-side rest timer, and the track writes a history.
// The helpers below are therefore mostly about the session lifecycle
// (start → sets → rest → effort → week close) rather than about scales.

// puOverdueAfter is the gap between the two — and only two — pings of one
// due cycle: the first at NextDueAt ("time to train"), the second this much
// later ("the session is still waiting"). After the second the program stays
// silent until a session moves NextDueAt again.
const puOverdueAfter = 4 * 24 * time.Hour

// puConsentSampleBase is the base the consent card's "≈ N minutes" line is
// computed from. The user has no base yet at that point and the alternative
// would be a hardcoded number inside a text — this keeps every number in the
// track derived from the generator.
const puConsentSampleBase = 15

// puSparkChars is the eight-step ramp of the progress screen's text
// sparkline (no image libraries in v1, by decision).
var puSparkChars = []rune("▁▂▃▄▅▆▇█")

// puSparkPoints is how many open sets the sparkline shows.
const puSparkPoints = 8

// isPushupState reports whether kind is one of the pu_* states. A deliberate
// enumeration, not a lookup over registered phases: the answer must not
// depend on wiring.
func isPushupState(kind state.StateKind) bool {
	switch kind {
	case state.StatePuConsent,
		state.StatePuGate,
		state.StatePuGoal,
		state.StatePuVariation,
		state.StatePuTest,
		state.StatePuMenu,
		state.StatePuSet,
		state.StatePuRest,
		state.StatePuEffort,
		state.StatePuWeekFork,
		state.StatePuRedCard,
		state.StatePuProgress,
		state.StatePuDeleteConfirm:
		return true
	}
	return false
}

// resumablePuState reports whether kind is a position inside a running
// session that a pause can meaningfully return to. Only these are ever
// recorded as PushupSession.ResumeState — the setup chain (consent, gate,
// goal, variation), the menu, the progress screen and the confirmations are
// re-entered through the menu instead.
func resumablePuState(kind state.StateKind) bool {
	return kind == state.StatePuSet ||
		kind == state.StatePuRest ||
		kind == state.StatePuEffort
}

// hasPuConsent reports whether the single track-wide consent was given. A
// stored program implies it — the program is created by the consent itself.
func hasPuConsent(u state.UserData) bool {
	return u.PuConsentAt != nil || u.Pushups != nil
}

// hasPuData reports whether anything of the track is stored — the /pushups_delete gate.
func hasPuData(u state.UserData) bool {
	return hasPuConsent(u) || u.PuTest != nil || u.PuSession != nil || len(u.PuHistory) > 0
}

// puSessionTTL is the content-driven lifetime of an unfinished session.
func puSessionTTL(c *screening.PushupContent) time.Duration {
	return time.Duration(c.Params.SessionTTLHours) * time.Hour
}

// puActiveSession returns the unfinished session when it is still resumable,
// nil when there is none or it has outlived the TTL. A stale session is
// closed (as a partial one) by puExpireSession on the next track entry.
func puActiveSession(c *screening.PushupContent, u state.UserData, now time.Time) *state.PushupSession {
	if u.PuSession == nil || u.PuSession.Stale(now, puSessionTTL(c)) {
		return nil
	}
	return u.PuSession
}

// puWorkoutSession returns the active session only when it is an ordinary
// workout — the resume row and the resume target of a max test differ (a
// test is one number, so it is simply re-offered rather than resumed).
func puWorkoutSession(c *screening.PushupContent, u state.UserData, now time.Time) *state.PushupSession {
	s := puActiveSession(c, u, now)
	if s == nil || s.Kind != state.PushupSessionWorkout {
		return nil
	}
	return s
}

// puEntryState is where the track is entered (the landing button and
// /pushups). The position is DERIVED from the stored program rather than
// remembered, exactly like the self-checks derive a question index from the
// recorded answers: consent → safety gate → goal → variation → first test →
// menu. An open max test outranks all of them.
func puEntryState(c *screening.PushupContent, u state.UserData, now time.Time) state.StateKind {
	if s := puActiveSession(c, u, now); s != nil && s.Kind != state.PushupSessionWorkout {
		return state.StatePuTest
	}
	p := u.Pushups
	switch {
	case p == nil || !hasPuConsent(u):
		return state.StatePuConsent
	case p.GateIdx < len(c.Gate.Questions):
		return state.StatePuGate
	case p.Goal == "":
		return state.StatePuGoal
	case p.Variation == "":
		return state.StatePuVariation
	case p.Base <= 0:
		return state.StatePuTest
	default:
		return state.StatePuMenu
	}
}

// puResumeTarget is where the landing's «Продолжить тренировку» button and
// the menu's resume row land: the recorded position of the open session,
// corrected for what has happened since — a rest whose timer has already
// expired continues at the next set, a session whose sets are all recorded
// continues at the self-report question.
func puResumeTarget(c *screening.PushupContent, u state.UserData, now time.Time) state.StateKind {
	s := puWorkoutSession(c, u, now)
	if s == nil {
		return puEntryState(c, u, now)
	}
	if len(s.Targets) > 0 && len(s.Actual) >= len(s.Targets) {
		return state.StatePuEffort
	}
	if s.ResumeState == state.StatePuRest && now.Before(s.RestUntil) {
		return state.StatePuRest
	}
	if resumablePuState(s.ResumeState) && s.ResumeState != state.StatePuRest {
		return s.ResumeState
	}
	return state.StatePuSet
}

// puResumeLabel renders the contextual resume row («подход 3/5»).
func puResumeLabel(c *screening.PushupContent, s *state.PushupSession) string {
	current, total := len(s.Actual)+1, len(s.Targets)
	if current > total {
		current = total
	}
	return renderContent(c.UI.ResumeButton, map[string]string{
		"current": strconv.Itoa(current),
		"total":   strconv.Itoa(total),
	})
}

// mutatePuProgram edits the program inside an Outcome.Mutate. state.Store
// hands out a struct copy that still shares pointers, so the program is
// CLONED before it is touched — the project-wide rule for every pointer
// field of UserData.
func mutatePuProgram(u *state.UserData, f func(*state.PushupProgram)) {
	if u.Pushups == nil {
		return
	}
	p := u.Pushups.Clone()
	f(p)
	u.Pushups = p
}

// mutatePuSession is the same for the transient session.
func mutatePuSession(u *state.UserData, f func(*state.PushupSession)) {
	if u.PuSession == nil {
		return
	}
	s := u.PuSession.Clone()
	f(s)
	u.PuSession = s
}

