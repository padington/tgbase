var (
	puRangeRe  = regexp.MustCompile(`(\d{1,4})\s*[-–—]\s*(\d{1,4})`)
	puNumberRe = regexp.MustCompile(`\d{1,4}`)
)

// parsePuReps reads a rep count out of whatever the user typed. The keyboard
// covers most taps; this covers the rest: "12 повторов", "~15", "12-13" (the
// SMALLER of a range — never credit the optimistic end), a bare number.
// Zero is a valid answer, not an error: it is a missed set, which the track
// records and moves on from. Anything without a number, or a number outside
// 0..max, is a re-ask.
func parsePuReps(in string, max int) (int, bool) {
	s := strings.TrimSpace(in)
	if m := puRangeRe.FindStringSubmatch(s); m != nil {
		lo, err1 := strconv.Atoi(m[1])
		hi, err2 := strconv.Atoi(m[2])
		if err1 != nil || err2 != nil {
			return 0, false
		}
		if hi < lo {
			lo = hi
		}
		return lo, lo >= 0 && lo <= max
	}
	m := puNumberRe.FindString(s)
	if m == "" {
		return 0, false
	}
	v, err := strconv.Atoi(m)
	if err != nil || v < 0 || v > max {
		return 0, false
	}
	return v, true
}

// puRepsKeyboard is the suggestion row for a fixed set: the target with its
// neighbours. Free input still works — these only save a keystroke.
func puRepsKeyboard(target int) []string {
	return puNumberRow([]int{target - 1, target, target + 1, target + 2})
}

// puOpenKeyboard is the suggestion row for the open set: the floor and a few
// steps above it, because the open set is where a good day shows up.
func puOpenKeyboard(floor int) []string {
	return puNumberRow([]int{floor, floor + 1, floor + 2, floor + 5})
}

// puNumberRow renders a keyboard row from numbers, dropping negatives and
// duplicates (they appear when the target is tiny).
func puNumberRow(values []int) []string {
	seen := map[int]bool{}
	out := make([]string, 0, len(values))
	for _, v := range values {
		if v < 0 || seen[v] {
			continue
		}
		seen[v] = true
		out = append(out, strconv.Itoa(v))
	}
	return out
}

