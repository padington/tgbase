func TestPushupNextEffortAdj(t *testing.T) {
	c := loadPushups(t)
	e := &c.Params.EffortAdj

	if got := c.NextEffortAdj(1, PushupEffortHard); got != 1+e.Hard {
		t.Errorf("hard: %v, want %v", got, 1+e.Hard)
	}
	if got := c.NextEffortAdj(1, PushupEffortOK); got != 1 {
		t.Errorf("ok: %v, want 1", got)
	}
	if got := c.NextEffortAdj(1, PushupEffortEasy); got != 1+e.Easy {
		t.Errorf("easy: %v, want %v", got, 1+e.Easy)
	}
	if got := c.NextEffortAdj(0, PushupEffortOK); got != 1 {
		t.Errorf("an unset adjustment must start from 1, got %v", got)
	}
	if got := c.NextEffortAdj(1, "shrug"); got != 1 {
		t.Errorf("an unknown answer must not move the adjustment: %v", got)
	}

	// Accumulates, but stays inside the clamp however many times it is asked.
	v := 1.0
	for i := 0; i < 20; i++ {
		v = c.NextEffortAdj(v, PushupEffortEasy)
	}
	if v != e.Max {
		t.Errorf("twenty easy sessions gave %v, want the clamp %v", v, e.Max)
	}
	for i := 0; i < 20; i++ {
		v = c.NextEffortAdj(v, PushupEffortHard)
	}
	if v != e.Min {
		t.Errorf("twenty hard sessions gave %v, want the clamp %v", v, e.Min)
	}
}

func TestPushupVariationLadder(t *testing.T) {
	c := loadPushups(t)
	ladder := c.Variations.Ladder
	easiest, hardest := ladder[0].ID, ladder[len(ladder)-1].ID

	if c.VariationIndex("nope") != -1 {
		t.Error("an unknown rung must report -1")
	}
	if c.Variation("nope") != nil {
		t.Error("an unknown rung must resolve to nil")
	}
	if got := c.ShiftVariation("nope", -1); got != c.Variations.DefaultID {
		t.Errorf("an unknown rung must fall back to the default, got %q", got)
	}
	if got := c.ShiftVariation(easiest, -3); got != easiest {
		t.Errorf("stepping below the easiest rung gave %q", got)
	}
	if got := c.ShiftVariation(hardest, +3); got != hardest {
		t.Errorf("stepping above the hardest rung gave %q", got)
	}

	mid := c.Variations.DefaultID
	down := c.ShiftVariation(mid, -c.Params.JointPainStepDown)
	if c.VariationIndex(down) != c.VariationIndex(mid)-c.Params.JointPainStepDown {
		t.Errorf("a pain step down landed on %q", down)
	}
	if up := c.ShiftVariation(mid, +1); c.VariationIndex(up) != c.VariationIndex(mid)+1 {
		t.Errorf("a step up landed on %q", up)
	}

	offered := c.OfferedVariations()
	if len(offered) < 2 || len(offered) >= len(ladder) {
		t.Errorf("the pick list has %d of %d rungs", len(offered), len(ladder))
	}
	for _, v := range offered {
		if !v.Offered {
			t.Errorf("rung %q is in the pick list but not marked offered", v.ID)
		}
	}
}

func TestPushupEstimateMinutes(t *testing.T) {
	c := loadPushups(t)
	plan := c.Plan(PlanInput{Base: 20, DayIdx: 1, EffortAdj: 1})
	got := c.EstimateMinutes(plan)
	if got < 5 || got > 20 {
		t.Errorf("a base-20 session estimates at %d minutes", got)
	}
	if c.EstimateMinutes(PushupPlan{}) != 0 {
		t.Error("an empty plan must estimate at zero minutes")
	}
	heavier := c.EstimateMinutes(c.Plan(PlanInput{Base: 40, DayIdx: 2, EffortAdj: 1.15, SessionsDone: 40}))
	if heavier <= got {
		t.Errorf("a heavier session estimates at %d minutes, not above %d", heavier, got)
	}
}

