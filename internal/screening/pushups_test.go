func TestPushupClassifyTest(t *testing.T) {
	c := loadPushups(t)
	p := &c.Params

	normal := c.ClassifyTest(17, true)
	if normal.Base != 17 || normal.Capped || normal.TooLow {
		t.Errorf("a plain result of 17 became %+v", normal)
	}

	capped := c.ClassifyTest(p.TestCap+40, true)
	if !capped.Capped || capped.Base != p.TestCap {
		t.Errorf("a result above the ceiling became %+v, want capped at %d", capped, p.TestCap)
	}
	if edge := c.ClassifyTest(p.TestCap-1, true); edge.Capped {
		t.Errorf("%d reps must not be capped", p.TestCap-1)
	}

	tooLow := c.ClassifyTest(p.TooLowReps, true)
	if !tooLow.TooLow || !tooLow.StepDown {
		t.Errorf("%d reps must step down the ladder, got %+v", p.TooLowReps, tooLow)
	}
	if tooLow.Base != p.MinBase {
		t.Errorf("a too-low result must floor the base at %d, got %d", p.MinBase, tooLow.Base)
	}
	if onEasiest := c.ClassifyTest(0, false); onEasiest.StepDown || onEasiest.Base != p.MinBase {
		t.Errorf("on the easiest rung there is nowhere to step down: %+v", onEasiest)
	}
	if ok := c.ClassifyTest(p.TooLowReps+1, true); ok.TooLow {
		t.Errorf("%d reps is a valid base, not a too-low result", p.TooLowReps+1)
	}
}

